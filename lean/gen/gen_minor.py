"""Generate N5R2/Minor.lean: H <= phi2(t) = 1/(2-2t) on [-1,1), equality exactly at -1, -1/2, 0, for the H of
cert_n5_s2_short.json.  Proof shape: 1 - (2-2t) H(t) = (t+1)(2t+1)^2 t^2 q(t) (ring), and
q(t) - b = sum_i (b_i - b) C(6,i) a^i c^(6-i) with a = (1+t)/2, c = (1-t)/2 (Bernstein, ring), all b_i - b >= 0."""
import json, sys, sympy as sy
from fractions import Fraction as Fr
C = json.load(open(sys.argv[1])); out = sys.argv[2]
t = sy.symbols('t')
H = sy.expand(sum(sy.Rational(Fr(c).numerator, Fr(c).denominator) * sy.chebyshevt(j, t) for j, c in enumerate(C['H_chebyshev'])))
Hc = [sy.Poly(H, t).coeff_monomial(t**k) for k in range(11)]
p = sy.Poly(sy.expand(1 - (2 - 2*t) * H), t)
q, r = sy.div(p, sy.Poly((t+1)*(2*t+1)**2*t**2, t)); assert r.is_zero
n = q.degree(); qc = [q.coeff_monomial(t**k) for k in range(n + 1)]
x = sy.symbols('x'); qx = sy.Poly(sy.expand(q.as_expr().subs(t, -1 + 2*x)), x)
cx = [qx.coeff_monomial(x**k) for k in range(n + 1)]
b = [sum(sy.binomial(i, k) / sy.binomial(n, k) * cx[k] for k in range(i + 1)) for i in range(n + 1)]
bmin = sy.Rational(1, 100); assert all(v > bmin for v in b)
def lit(v):
    v = sy.Rational(v); p_, q_ = v.p, v.q
    return f"({p_} : ℝ)" if q_ == 1 else f"(({p_} : ℝ) / {q_})"
def poly(cs, var="t"):
    return " + ".join(f"{lit(c)} * {var} ^ {k}" for k, c in enumerate(cs) if c != 0)
bern = " + ".join(f"{lit(b[i] - bmin)} * {sy.binomial(n, i)} * ((1 + t) / 2) ^ {i} * ((1 - t) / 2) ^ {n - i}" for i in range(n + 1))
lean = f'''import Mathlib

/-!
# N = 5, Riesz s = 2: the one-dimensional minorant `H ≤ φ₂` on `[-1, 1)`

`Hpoly` is the degree-10 polynomial `H` of the three-point certificate (`cert_n5_s2_short.json`, monomial form). With
`φ₂(t) = 1/(2-2t)`:
* `1 - (2-2t) H(t) = (t+1)(2t+1)² t² q(t)` (`factor`);
* `q(t) - 1/100 = Σ (bᵢ - 1/100) C(6,i) ((1+t)/2)ⁱ ((1-t)/2)⁶⁻ⁱ` with all `bᵢ - 1/100 ≥ 0` (Bernstein form, `q_bern`), so
  `q > 0` on `[-1, 1]` (`q_pos`).

Hence `H ≤ φ₂` on `[-1, 1)`, with equality exactly at `t ∈ {{-1, -1/2, 0}}` (`H_le`, `H_eq_iff`).
Generated by `lean/gen/gen_minor.py`.  Regenerate; do not edit.
-/

namespace N5R2

/-- The polynomial `H` of the certificate. -/
noncomputable def Hpoly (t : ℝ) : ℝ :=
  {poly(Hc)}

/-- The cofactor `q` with `1 - (2-2t) H = (t+1)(2t+1)² t² q`. -/
noncomputable def qpoly (t : ℝ) : ℝ :=
  {poly(qc)}

theorem factor (t : ℝ) : 1 - (2 - 2 * t) * Hpoly t = (t + 1) * (2 * t + 1) ^ 2 * t ^ 2 * qpoly t := by
  unfold Hpoly qpoly; ring

theorem q_bern (t : ℝ) : qpoly t - 1 / 100 =
    {bern} := by
  unfold qpoly; ring

theorem q_pos {{t : ℝ}} (h1 : -1 ≤ t) (h2 : t ≤ 1) : 0 < qpoly t := by
  have ha : 0 ≤ (1 + t) / 2 := by linarith
  have hc : 0 ≤ (1 - t) / 2 := by linarith
  have hb := q_bern t
  have : 0 ≤ qpoly t - 1 / 100 := by rw [hb]; positivity
  linarith

/-- **`H ≤ φ₂` on `[-1, 1)`.** -/
theorem H_le {{t : ℝ}} (h1 : -1 ≤ t) (h2 : t < 1) : Hpoly t ≤ 1 / (2 - 2 * t) := by
  have hd : 0 < 2 - 2 * t := by linarith
  rw [le_div_iff₀ hd]
  have hf := factor t
  have hq := q_pos h1 h2.le
  have : 0 ≤ (t + 1) * (2 * t + 1) ^ 2 * t ^ 2 * qpoly t := by
    have : 0 ≤ t + 1 := by linarith
    positivity
  nlinarith

/-- Equality holds exactly at the inner products of the triangular bipyramid. -/
theorem H_eq_iff {{t : ℝ}} (h1 : -1 ≤ t) (h2 : t < 1) :
    Hpoly t = 1 / (2 - 2 * t) ↔ t = -1 ∨ t = -1 / 2 ∨ t = 0 := by
  have hd : 0 < 2 - 2 * t := by linarith
  have hq := q_pos h1 h2.le
  have hf := factor t
  constructor
  · intro h
    have h0 : (t + 1) * (2 * t + 1) ^ 2 * t ^ 2 * qpoly t = 0 := by
      rw [← hf, h, mul_one_div_cancel hd.ne', sub_self]
    have hqne : qpoly t ≠ 0 := hq.ne'
    rcases mul_eq_zero.1 h0 with h0 | h0
    · rcases mul_eq_zero.1 h0 with h0 | h0
      · rcases mul_eq_zero.1 h0 with h0 | h0
        · left; linarith
        · right; left; have := pow_eq_zero_iff (n := 2) (by norm_num) |>.1 h0; linarith
      · right; right; exact pow_eq_zero_iff (n := 2) (by norm_num) |>.1 h0
    · exact absurd h0 hqne
  · intro h
    have h0 : (t + 1) * (2 * t + 1) ^ 2 * t ^ 2 * qpoly t = 0 := by
      rcases h with h | h | h <;> subst h <;> ring
    rw [← hf] at h0
    rw [eq_div_iff hd.ne']
    linarith

end N5R2
'''
open(out, 'w').write(lean)
print("wrote", out, "bmin=1/100, min b_i =", float(min(b)), " H coefficient max bits:",
      max(max(abs(sy.Rational(v).p).bit_length(), sy.Rational(v).q.bit_length()) for v in Hc))
